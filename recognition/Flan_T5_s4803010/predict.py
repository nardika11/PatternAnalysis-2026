import argparse
import torch
from modules import FLANT5
from dataset import BioLaySummData

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

FULL_PATH = "recognition/Flan_T5_s4803010/models/FlanT5_full_lr1e-05"
LORA_PATH = "recognition/Flan_T5_s4803010/models/FlanT5_lora_lr0.0001"

def predict(model, data, report):
    """Generates a layman summary of the provided radiology report"""

    # Apply the LLM instruction prompt
    inputText = data.prefix + report

    # Tokenise the input
    inputs = data.tokeniser(inputText, truncation=True, return_tensors="pt", 
                            max_length=data.maxInputTokens).to(device)

    # Generate the summary
    with torch.no_grad(): 
        outputs = model.generate(**inputs, max_new_tokens=256, no_repeat_ngram_size=5, do_sample=False)

    # Decode the summary
    summary = data.tokeniser.decode(outputs[0], skip_special_tokens=True)

    return summary

def main():
    """Handles processing the command line arguments to generate the radiology report"""
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", choices=["untuned", "full", "lora"], default="full")
    parser.add_argument("--report", default="No signs of metastatic disease or significant changes " \
                                            "compared to the previous control study are identified.")
    args = parser.parse_args()

    # Load the tokeniser and model
    data = BioLaySummData()
    data.load_tokeniser()

    model = FLANT5(useLora=(args.model=="lora"))

    # Load the save fine-tuned checkpoint
    if args.model != "untuned":
        path = FULL_PATH if args.model == "full" else LORA_PATH
        model.load_tuned_model(path)

    model.to(device)
    model.eval()

    summary = predict(model, data, args.report)

    print(f"Original Report: {args.report}")
    print(f"Summary: {summary}")

    # Safety Warning
    print("WARNING: This summary was generated by an LLM and may contain missing and/or " \
          "incorrect information. It should not be considered as official medical advice " \
          "without verification from a medical professional")
    
if __name__ == "__main__":
    main()